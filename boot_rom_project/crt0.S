    .section .init
    .globl _start

# ===========================================================
# UART
# ===========================================================
    .equ UART_BASE, 0x80000200
    .equ UART_PRE,  0x00
    .equ UART_STP,  0x04
    .equ UART_RDR,  0x08
    .equ UART_TDR,  0x0C
    .equ UART_CFG,  0x10

# ===========================================================
# QSPI
# ===========================================================
    .equ QSPI_BASE, 0x80000500
    .equ QSPI_CCR,  0x00
    .equ QSPI_ADR,  0x04
    .equ QSPI_DR,   0x08
    .equ QSPI_STA,  0x0C
    .equ QSPI_FCR,  0x10
    .equ QSPI_DONE, 1

# ===========================================================
# RAM DEST
# ===========================================================
    .equ RAM_BASE, 0x20000000

# ===========================================================
# ENTRY
# ===========================================================
_start:

# -----------------------------------------------------------
# UART INIT (DO THIS FIRST)
# -----------------------------------------------------------
    li t0, UART_BASE

    li t1, 217
    sw t1, UART_PRE(t0)

    li t1, 0
    sw t1, UART_STP(t0)

# -----------------------------------------------------------
# QSPI SETUP
# -----------------------------------------------------------
    li s0, QSPI_BASE
    li s1, RAM_BASE
    li s2, 32              # 32 blocks

    li s3, 0x00000000      # flash addr
    li s4, 0x00000100      # 256 bytes step

# ===========================================================
# MAIN LOOP
# ===========================================================
qspi_block_loop:

# -----------------------------------------------------------
# set flash address (ONLY ONCE PER LOOP)
# -----------------------------------------------------------
    sw s3, QSPI_ADR(s0)
    fence
    add s3, s3, s4

# -----------------------------------------------------------
# flush FIFO
# -----------------------------------------------------------
    li t0, (1 << 0) | (1 << 1)
    sw t0, QSPI_FCR(s0)

# -----------------------------------------------------------
# configure QSPI read (256 bytes)
# -----------------------------------------------------------

    li t1, 0x6C

    li t2, (3 << 8)
    or  t1, t1, t2

    li t2, (0 << 10)
    or  t1, t1, t2

    li t2, (8 << 11)
    or  t1, t1, t2

    li t2, (255 << 16)
    or  t1, t1, t2

    li t2, (1 << 25)
    or  t1, t1, t2

    sw t1, QSPI_CCR(s0)

# -----------------------------------------------------------
# start transfer
# -----------------------------------------------------------
    li t0, 0xABCD
    sw t0, QSPI_DR(s0)

# -----------------------------------------------------------
# wait done
# -----------------------------------------------------------
wait_done:
    lw t0, QSPI_STA(s0)
    andi t0, t0, 1
    beqz t0, wait_done

# -----------------------------------------------------------
# read 256 bytes -> RAM
# -----------------------------------------------------------
    li t3, 64

read_loop:
    lw t0, QSPI_DR(s0)
    sw t0, 0(s1)

    addi s1, s1, 4
    addi t3, t3, -1
    bnez t3, read_loop

# -----------------------------------------------------------
# next block
# -----------------------------------------------------------
    addi s2, s2, -1
    bnez s2, qspi_block_loop

# ===========================================================
# SUCCESS MESSAGE
# ===========================================================
    li t2, 0x4F
    jal ra, uart_send

    li t2, 0x4B
    jal ra, uart_send

    li t2, 0x0A
    jal ra, uart_send

# ===========================================================
# JUMP TO LOADED IMAGE
# ===========================================================
    li t0, 0x80000000
    jr t0

# ===========================================================
# UART SEND
# ===========================================================
uart_send:
    li t0, UART_BASE

    sw t2, UART_TDR(t0)

    li t1, 1
    sw t1, UART_CFG(t0)

    li t1, 0
    sw t1, UART_CFG(t0)

wait_tx:
    lw t1, UART_CFG(t0)
    andi t1, t1, 4
    beqz t1, wait_tx

    ret

# ===========================================================
# STACK (optional)
# ===========================================================
    .section .stack
    .align 4
    .globl _stack_top
_stack_top:
    .space 256